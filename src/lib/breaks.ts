// 원문 줄바꿈 되살리기. 글자는 바꾸지 않고 줄바꿈("\n")만 넣는다. 화면에서는 white-space: pre-line 인 칸에 넣는다.
// 관광공사 응답을 옮기는 사이에 줄바꿈이 빠져 앞 줄 끝과 다음 줄 첫머리가 붙은 자리를 나눈다.

/**
 * 이용시간·쉬는 날: 줄 첫머리가 아닌 "- " 앞과 "[" 앞에서 줄을 나눈다.
 * 예: "- 하절기(4월~9월) 09:00~18:00- 동절기(10월~3월) 09:00~17:00" → 두 줄.
 * 해당: 옥산서원, 무열왕릉, 분황사, 오릉, 석굴암, 첨성대, 동궁원(이용시간·쉬는 날), 국립경주박물관, 대릉원, 솔거미술관, 화랑마을.
 * 앞 글자 뒤의 빈칸은 그대로 두고(pre-line 이라 줄 끝 빈칸은 보이지 않음) 그 뒤에 줄바꿈을 넣는다.
 */
export function hoursLines(t: string): string;
export function hoursLines(t: string | null): string | null;
export function hoursLines(t: string | null): string | null {
  if (!t) return t;
  return t.replace(/(\S)([ \t]*)(- |\[)/g, "$1$2\n$3");
}
// (요금 칸: 이용요금·시설이용료·주차요금 글에도 쓴다. 예: 동궁원 "[식물원 (개인)]- 경주시민 2,000원- 어른 …")

/**
 * 관광정보 소개·반복 정보의 그 밖의 칸(introExtra.ts rows): 앞 글자에 빈칸 없이 바로 붙은 "- "·"[" 앞에서만 줄을 나눈다.
 * 예: 화랑마을 내국인 예약안내 "… 홈페이지에서 가능- 화랑마을 대관예약 …" → 두 줄.
 * hoursLines보다 좁게 잡은 것은 등산로 글("경비실 - 빌라동")처럼 빈칸을 둔 "- "가 줄 머리가 아닌 글이 있어서다.
 * (요금 칸은 hoursLines를 쓴다.)
 */
export function gluedLines(t: string): string {
  return t.replace(/(\S)(- |\[)/g, "$1\n$2");
}

/**
 * 무장애 여행 정보 글: 붙은 자리를 나눈다. 글이 곳마다 달라 규칙 대신 붙은 자리를 하나씩 적었다(앞 글자 | 뒤 글자).
 * 같은 꼴의 글이 줄바꿈된 채 들어 있는 곳(김유신묘 주차 "주차 가능 : 2대.\n주변 휠체어 …")을 보고 줄을 나눴다.
 */
const BF_JOINS: [string, string][] = [
  ["2대", "주변"], // 오릉 주차("2대주변"), 경주월드 주차("12대주변")
  ["있음", "경사로"], // 오릉 주차
  ["없음.", "장애인"], // 오릉 주차
  ["평지임", "경사로로"], // 오릉 접근로
  ["있음", "출입통로"], // 오릉 출입통로
  ["가능", "휠체어"], // 오릉 출입통로
  ["정류장", "저상버스"], // 오릉·경주월드 대중교통
  ["있음", "장애인"], // 불국사 접근로
  ["있음.", "관광지"], // 경주월드 주차
  ["가능", "관광지"], // 경주월드 접근로
  ["무료", "준비사항"], // 경주월드 휠체어
  ["표시.", "대변기"], // 경주월드 화장실
  ["있음", "시설관리자"], // 경주월드 화장실
  ["2000원", "신분증"], // 경주월드 유모차
];

export function bfLines(t: string): string;
export function bfLines(t: string | null): string | null;
export function bfLines(t: string | null): string | null {
  if (!t) return t;
  return BF_JOINS.reduce((s, [a, b]) => s.split(a + b).join(`${a}\n${b}`), t);
}
